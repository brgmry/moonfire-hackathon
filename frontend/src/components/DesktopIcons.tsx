"use client";
export type IconDef = { id: string; label: string; glyph: "doc" | "chart" | "people" | "disk" | "trash"; onOpen: () => void; tip?: string };

function Glyph({ g }: { g: IconDef["glyph"] }) {
  // 1-bit icons, 24x24 pixel grid drawn with rects.
  const p: Record<IconDef["glyph"], string[]> = {
    doc: ["..##########....", "..#........##...", "..#........#.#..", "..#........####.", "..#..#####....#.", "..#...........#.", "..#..#####....#.", "..#...........#.", "..#..#######..#.", "..#...........#.", "..#..#######..#.", "..#...........#.", "..#############.", "................"],
    chart: ["..#############.", "..#...........#.", "..#......#....#.", "..#......#....#.", "..#..#...#....#.", "..#..#...#..#.#.", "..#..#.#.#..#.#.", "..#..#.#.#..#.#.", "..#.##.#.#.##.#.", "..#.##.#.#.##.#.", "..#############.", "....#.......#...", "....#.......#...", "................"],
    people: ["................", ".....####.......", "....#....#......", "....#....#..###.", ".....####..#...#", "...########.#...#", "..#........#.###", "..#........#.#.#", "..#........#.#.#", "..#........####.", "..##########....", "................", "................", "................"],
    disk: ["..#############.", "..#.#########.#.", "..#.#.......#.#.", "..#.#.......#.#.", "..#.#########.#.", "..#...........#.", "..#...........#.", "..#..#######..#.", "..#..#.....#..#.", "..#..#.....#..#.", "..#..#######..#.", "..#############.", "................", "................"],
    trash: ["......####......", "...##########...", "...#........#...", "...##########...", "....#......#....", "....#.#.#..#....", "....#.#.#..#....", "....#.#.#..#....", "....#.#.#..#....", "....#.#.#..#....", "....#.#.#..#....", "....#......#....", "....########....", "................"],
  };
  return (
    <svg viewBox="0 0 16 14" width="40" height="35" shapeRendering="crispEdges" aria-hidden="true">
      {p[g].flatMap((row, y) => row.split("").map((c, x) => c === "#" ? <rect key={`${x}-${y}`} x={x} y={y} width="1" height="1" fill="#141414" /> : null))}
    </svg>
  );
}

export function DesktopIcons({ icons }: { icons: IconDef[] }) {
  return (
    <nav className="icons" aria-label="desktop">
      {icons.map((i) => (
        <button key={i.id} type="button" className="icon" onClick={i.onOpen} data-tip={i.tip ?? `open ${i.label}`}>
          <span className="glyph"><Glyph g={i.glyph} /></span>
          <span className="lbl">{i.label}</span>
        </button>
      ))}
    </nav>
  );
}
